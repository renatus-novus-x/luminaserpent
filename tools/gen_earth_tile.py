#!/usr/bin/env python3
"""Generate earth_bg.h: compile & run tools/earth_gen.cpp, crop the
Earth bounding box (209x209 around EARTH_CX/EARTH_CY), downscale to
105x105 (the game blits it back at 2x), and emit GRB555 data."""
import subprocess, sys
from PIL import Image

CX, CY, M = 388, 238, 104
subprocess.run(["g++", "-O2", "-o", "/tmp/earth_gen", "tools/earth_gen.cpp"], check=True)
subprocess.run(["/tmp/earth_gen"], check=True, cwd="/tmp")
im = Image.open("/tmp/bgcache.ppm").crop((CX - M, CY - M, CX + M + 1, CY + M + 1))
im = im.resize((105, 105), Image.LANCZOS)
px = im.load()
vals = []
for y in range(105):
    for x in range(105):
        r, g, b = px[x, y]
        r5, g5, b5 = round(r * 31 / 255), round(g * 31 / 255), round(b * 31 / 255)
        vals.append(((g5 & 31) << 11) | ((r5 & 31) << 6) | ((b5 & 31) << 1) | 1)
with open("earth_bg.h", "w") as f:
    f.write("/* earth_bg.h - pre-rendered Earth tile (105x105, GRB555),\n")
    f.write("   generated by tools/gen_earth_tile.py - do not edit by hand. */\n")
    f.write("static const uint16_t EARTH_TILE[105 * 105] = {\n")
    for i in range(0, len(vals), 10):
        f.write("  " + ",".join(str(v) for v in vals[i:i + 10]) + ",\n")
    f.write("};\n")
print("earth_bg.h written:", len(vals), "pixels")
