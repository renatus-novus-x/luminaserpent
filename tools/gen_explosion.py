#!/usr/bin/env python3
"""Bake the game's explosion set into explosion_fx.h.

Two pixelfx effects (MIT, (c) Patch -- https://github.com/patch-gg/
pixelfx), rendered to sprite sheets by pixelfx's own Node exporter,
recoloured to the warm ramp approved for this game (cyan->yellow,
blue->orange, purple->red, white flash untouched), downscaled,
pre-blended over the game's deep-space background colour and
quantised to GRB555.  Each frame is span-encoded: per row a list of
(x0, len, pixel-offset) runs over a shared uint16 pixel pool, so the
runtime only writes the pixels that are actually visible.

Assignment (user decision, 2026-11-02):
  normal enemies  -> firework-burst  (FX_FW_S 72x64, FX_FW_M 96x84)
  boss explosions -> plasma-explosion (FX_PL_M 96x84: shards and the
                     dying barrage; FX_PL_L 124x110: final blast and
                     the post-whiteout bloom)
Both effects are baked at 15 frames so the combined set still fits
the 1 MB-machine footprint budget.

Usage: gen_explosion.py [records root] [out.h]
Default records root: ~/workspace/x68k/pixelfx-test/pixelfx/records
"""
import json, sys
from pathlib import Path
import numpy as np
from PIL import Image

ROOT = Path(sys.argv[1]) if len(sys.argv) > 1 else Path.home() / \
    'workspace/x68k/pixelfx-test/pixelfx/records'
OUT = Path(sys.argv[2]) if len(sys.argv) > 2 else \
    Path(__file__).resolve().parent.parent / 'explosion_fx.h'

def sample(lo, hi, n):
    return [round(lo + i * (hi - lo) / (n - 1)) for i in range(n)]

NFRAMES = 15
# tag, effect, w, h, source-frame window (30 fps), centre-on-burst
SETS = [
    ('FW_S', 'firework-burst',   72,  64, sample(14, 48, NFRAMES), True),
    ('FW_M', 'firework-burst',   96,  84, sample(14, 48, NFRAMES), True),
    ('PL_M', 'plasma-explosion', 96,  84, sample(0, 17, NFRAMES), False),
    ('PL_L', 'plasma-explosion', 124, 110, sample(0, 17, NFRAMES), False),
]
BG = np.array([8.0, 16.0, 57.0])             # GRB(1,2,7) in 8-bit RGB
ALPHA_MIN = 28


def warm(im):
    a = np.asarray(im).copy()
    hsv = np.asarray(Image.fromarray(a[:, :, :3], 'RGB').convert('HSV')).astype(np.float32)
    h = hsv[:, :, 0] * 360.0 / 255.0
    m = (h >= 160) & (h <= 310)
    h2 = h.copy(); h2[m] = 50.0 - (h[m] - 160.0) * (50.0 / 150.0)
    hsv[:, :, 0] = h2 * 255.0 / 360.0
    hsv[:, :, 1] = np.clip(hsv[:, :, 1] * 1.05, 0, 255)
    a[:, :, :3] = np.asarray(Image.fromarray(hsv.astype(np.uint8), 'HSV').convert('RGB'))
    return Image.fromarray(a, 'RGBA')


def load_effect(name, centre):
    rec = ROOT / 'explosions' / name
    meta = json.loads((rec / f'{name}.json').read_text())
    sheet = Image.open(rec / f'{name}.png').convert('RGBA')
    src = []
    for f in meta['frames']:
        r = f['frame']
        src.append(sheet.crop((r['x'], r['y'], r['x'] + r['w'], r['y'] + r['h'])))
    if centre:
        # centre a 224x200 window on the burst (alpha centroid of the
        # peak-mass frame), so off-centre effects sit on the enemy
        peak = max(src, key=lambda im: float(np.asarray(im)[:, :, 3].sum()))
        a = np.asarray(peak)[:, :, 3].astype(np.float32)
        ys, xs = np.mgrid[0:a.shape[0], 0:a.shape[1]]
        cx = int((a * xs).sum() / a.sum()); cy = int((a * ys).sum() / a.sum())
        x0 = min(max(cx - 112, 0), src[0].width - 224)
        y0 = min(max(cy - 100, 0), src[0].height - 200)
        src = [f.crop((x0, y0, x0 + 224, y0 + 200)) for f in src]
    return [warm(f) for f in src]


cache = {}
for _, eff, _, _, _, centre in SETS:
    if eff not in cache:
        cache[eff] = load_effect(eff, centre)

out = []
out.append('/* explosion_fx.h -- GENERATED by tools/gen_explosion.py; do not edit.')
out.append('   Warm explosions baked from the pixelfx "firework-burst" and')
out.append('   "plasma-explosion" effects (MIT, (c) Patch,')
out.append('   https://github.com/patch-gg/pixelfx): hue-remapped to the')
out.append('   game\'s warm ramp, pre-blended over the deep-space background')
out.append('   colour, GRB555, span-encoded. */')
out.append('#pragma once')
out.append('#include <stdint.h>')
out.append('')
out.append(f'#define FX_FRAMES {NFRAMES}')
out.append('struct FxKind { int w, h; const uint32_t *foff; const uint32_t *poff;')
out.append('                const uint8_t *rowct; const uint32_t *spans; const uint16_t *pix; };')
out.append('')

total_bytes = 0
kind_rows = []
for tag, eff, tw, th, use, _ in SETS:
    frames = cache[eff]
    pix = []            # uint16 words, all frames concatenated
    poff = [0]
    spans = []          # uint32 packed: pix_off | x0<<16 | len<<24
    foff = [0]
    rowct = []          # uint8 per row per frame
    for fi in use:
        a = np.asarray(frames[fi].resize((tw, th), Image.LANCZOS)).astype(np.float32)
        alpha = a[:, :, 3] / 255.0
        blend = a[:, :, :3] * alpha[:, :, None] + BG * (1 - alpha[:, :, None])
        q = np.round(blend / 255.0 * 31).astype(np.uint16)
        words = (q[:, :, 1] << 11) | (q[:, :, 0] << 6) | (q[:, :, 2] << 1) | 1
        vis = a[:, :, 3] >= ALPHA_MIN
        frame_pix_start = len(pix)
        for r in range(th):
            row = vis[r]
            nsp = 0
            x = 0
            while x < tw:
                if row[x]:
                    x0 = x
                    while x < tw and row[x]:
                        pix.append(int(words[r, x])); x += 1
                    run_off = len(pix) - (x - x0) - frame_pix_start
                    spans.append(run_off | (x0 << 16) | ((x - x0) << 24))
                    nsp += 1
                else:
                    x += 1
            rowct.append(nsp)
        poff.append(len(pix))
        foff.append(len(spans))
    def emit(name, typ, vals, per=12):
        lines = [f'static const {typ} {name}[{len(vals)}] = {{']
        for i in range(0, len(vals), per):
            lines.append('  ' + ','.join(str(v) for v in vals[i:i + per]) + ',')
        lines.append('};')
        return lines
    out += emit(f'FX_{tag}_PIX', 'uint16_t', pix, 10)
    out += emit(f'FX_{tag}_POFF', 'uint32_t', poff, 12)
    out += emit(f'FX_{tag}_FOFF', 'uint32_t', foff, 12)
    out += emit(f'FX_{tag}_SPANS', 'uint32_t', spans, 8)
    out += emit(f'FX_{tag}_ROWCT', 'uint8_t', rowct, 16)
    nbytes = len(pix) * 2 + len(spans) * 4 + len(rowct) + (len(poff) + len(foff)) * 4
    total_bytes += nbytes
    print(f'{tag} {tw}x{th} ({eff}): pix {len(pix)} spans {len(spans)} -> {nbytes/1024:.1f} KiB')
    kind_rows.append(f'  {{ {tw}, {th}, FX_{tag}_FOFF, FX_{tag}_POFF, FX_{tag}_ROWCT, FX_{tag}_SPANS, FX_{tag}_PIX }},')
out.append(f'static const FxKind FX_KINDS[{len(SETS)}] = {{')
out += kind_rows
out.append('};')
out.append('#define FX_FW_S 0')
out.append('#define FX_FW_M 1')
out.append('#define FX_PL_M 2')
out.append('#define FX_PL_L 3')
OUT.write_text('\n'.join(out) + '\n')
print(f'wrote {OUT} ({OUT.stat().st_size/1024:.0f} KiB text, {total_bytes/1024:.1f} KiB data)')
