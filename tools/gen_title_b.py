#!/usr/bin/env python3
"""Bake the B-design title art (user pick, 2026-11-01) for the X68000
build, following the MSX build's title route:
- logo_title_b.h : the logo as a 1-bit outline mask (PackBits per
  row). The game stamps it three times -- dim echo at x-14, mid echo
  at x-7, main cyan at x=0 -- which reproduces the approved mock's
  doubled letterforms with flat tones, exactly like the MSX bake.
  The pink beam is drawn with fills at runtime; the little ship on
  the beam is a tiny keyed GRB555 image in the same header.
- title_earth.h  : the title Earth disc (336x236 on screen, baked at
  half resolution 168x118 and blitted 2x like the in-game Earth
  tile), GRB555, 0x0000 = transparent, drawn at (88, 244).

Artwork layout reuses the candidate-board renderer in
design/gen_title_x68k_candidates.py so the bake matches the approved
mock (cand-B).

Usage: python3 tools/gen_title_b.py   (run from the repo root)
"""
import os
import sys
import numpy as np
from PIL import Image

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(ROOT, "design"))
import gen_title_x68k_candidates as cand

BG = (2, 4, 16)  # deep-space base (preview flattening only)
LOGO_Y0 = 40     # logo image top on screen (mock rows 40..235)


def grb555(rgb):
    r, g, b = (int(v) for v in rgb)
    return ((g // 8) << 11) | ((r // 8) << 6) | ((b // 8) << 1) | 1


def flatten_words(img_rgba, bg=BG):
    """RGBA -> GRB555 word list, alpha < 128 -> 0x0000."""
    a = np.asarray(img_rgba).astype(np.float32)
    alpha = a[..., 3] / 255.0
    words = []
    for yy in range(a.shape[0]):
        for xx in range(a.shape[1]):
            if alpha[yy, xx] < 0.5:
                words.append(0)
            else:
                al = alpha[yy, xx]
                rgb = a[yy, xx, :3] * al + np.array(bg) * (1 - al)
                words.append(grb555(rgb))
    return words


def packbits_row(data: bytes) -> bytes:
    out = bytearray()
    i, n = 0, len(data)
    while i < n:
        run = 1
        while i + run < n and data[i + run] == data[i] and run < 128:
            run += 1
        if run >= 3:
            out += bytes((257 - run, data[i]))
            i += run
        else:
            start = i
            i += run
            while i < n:
                r = 1
                while i + r < n and data[i + r] == data[i] and r < 128:
                    r += 1
                if r >= 3:
                    break
                i += r
                if i - start >= 128:
                    break
            out += bytes((i - start - 1,)) + data[start:i]
    return bytes(out)


def emit_header(path, guard, title, defines, arrays):
    with open(path, "w") as f:
        f.write(f"/* {title}\n * Generated by tools/gen_title_b.py. "
                "Do not edit by hand. */\n")
        f.write(f"#ifndef {guard}\n#define {guard}\n\n")
        for name, val in defines:
            f.write(f"#define {name} {val}\n")
        f.write("\n")
        for name, decl, values, per_line, fmt in arrays:
            f.write(f"static const {decl} {name}[{len(values)}] = {{\n")
            for i in range(0, len(values), per_line):
                chunk = values[i:i + per_line]
                f.write("  " + ",".join(fmt % v for v in chunk) + ",\n")
            f.write("};\n\n")
        f.write(f"#endif /* {guard} */\n")


def build_logo_mask():
    """Binary outline mask of LUMINA + SERPENT, cropped to rows
    LOGO_Y0..235 (the echoes are runtime x-offsets of this mask)."""
    lum, ser = cand.logo_masks()
    mask = Image.new("L", (cand.W, cand.H), 0)
    for word, x, y in ((lum, 42, cand.LUM_Y), (ser, 21, cand.SER_Y)):
        ol = cand.outline_of(word, 2).point(
            lambda v: 255 if v >= 128 else 0)
        layer = Image.new("L", (cand.W, cand.H), 0)
        layer.paste(ol, (x, y))
        mask = Image.fromarray(np.maximum(np.asarray(mask),
                                          np.asarray(layer)))
    return mask.crop((0, LOGO_Y0, cand.W, 236))


def build_ship():
    img = Image.new("RGBA", (cand.W, cand.H), (0, 0, 0, 0))
    cand.draw_ship_small(img, 452, cand.SER_Y - 6, 1.1)
    return img.crop((438, 125, 466, 139))  # 28x14 around the glyph


def build_earth():
    canvas = cand.starfield().convert("RGBA")
    canvas.alpha_composite(cand.earth_disc(256, 428, 168))
    return canvas.crop((88, 244, 424, 480))  # 336x236 on-screen area


def main():
    mask = build_logo_mask()
    bits = (np.asarray(mask) > 0).astype(np.uint8)
    packed_bits = np.packbits(bits, axis=1)
    packed = bytearray()
    for r in range(packed_bits.shape[0]):
        packed += packbits_row(packed_bits[r].tobytes())
    ship_words = flatten_words(build_ship())
    emit_header(
        os.path.join(ROOT, "logo_title_b.h"), "LOGO_TITLE_B_H",
        "B-design title logo: 1-bit outline mask (PackBits per row)\n"
        " * + the beam ship as a keyed GRB555 image (0 = transparent).",
        [("LOGO_B_W", bits.shape[1]), ("LOGO_B_H", bits.shape[0]),
         ("LOGO_B_Y", LOGO_Y0), ("SHIP_B_W", 28), ("SHIP_B_H", 14),
         ("SHIP_B_X", 438), ("SHIP_B_Y", 125)],
        [("LOGO_B_MASK_PACKED", "uint8_t", list(packed), 12, "0x%02X"),
         ("SHIP_B_IMG", "uint16_t", ship_words, 7, "0x%04X")])
    print(f"logo mask: {bits.shape[1]}x{bits.shape[0]}, "
          f"packed {len(packed)} bytes (raw {packed_bits.size})")

    earth = build_earth().resize((168, 118), Image.LANCZOS)
    ewords = flatten_words(earth)
    emit_header(
        os.path.join(ROOT, "title_earth.h"), "TITLE_EARTH_H",
        "Title Earth disc (half resolution, blitted 2x),\n"
        " * GRB555, 0x0000 = transparent.",
        [("TITLE_EARTH_W", 168), ("TITLE_EARTH_H", 118)],
        [("TITLE_EARTH", "uint16_t", ewords, 8, "0x%04X")])
    print(f"earth: 168x118 tile, {len(ewords) * 2} bytes raw")

    # preview: starfield + earth + stamped echoes + beam + ship,
    # coloured exactly as the runtime stamps them
    prev = cand.starfield().convert("RGBA")
    prev.alpha_composite(cand.earth_disc(256, 428, 168))
    arr = np.asarray(prev.convert("RGB")).astype(np.float32)
    tones = [(-14, (0, 69, 83)), (-7, (1, 104, 111)),
             (0, (0, 227, 227))]
    full = np.zeros((cand.H, cand.W), dtype=np.uint8)
    full[LOGO_Y0:236] = bits
    for dx, rgb in tones:
        ys, xs = np.nonzero(full)
        for yy, xx in zip(ys, xs):
            nx = xx + dx
            if 0 <= nx < cand.W:
                arr[yy, nx] = rgb
    prev = Image.fromarray(np.clip(arr, 0, 255).astype(np.uint8))
    prev = prev.convert("RGBA")
    cand.draw_beam(prev, cand.SER_Y - 6)
    prev.alpha_composite(build_ship(), (438, 125))
    prev.convert("RGB").save(os.path.join(ROOT, "design",
                                          "title-b-preview.png"))
    print("preview: design/title-b-preview.png")


if __name__ == "__main__":
    main()
